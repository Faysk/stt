const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'web');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const meta = name => {
  const matches = [...html.matchAll(/<meta\s+(?:name|property)="([^"]+)"\s+content="([^"]*)"[^>]*>/g)].filter(m => m[1] === name);
  assert.equal(matches.length, 1, `Exactly one ${name}`);
  return matches[0][2];
};
assert.match(html, /<link rel="canonical" href="https:\/\/stt\.faysk\.dev\/">/);
assert.equal(meta('og:url'), 'https://stt.faysk.dev/');
assert.equal(meta('robots'), 'index,follow');
assert.match(meta('og:title'), /^stt \/ faysk/);
assert.equal(meta('twitter:card'), 'summary_large_image');
assert.equal(meta('twitter:image'), meta('og:image'));
assert.match(meta('og:image:alt'), /^stt/);
const image = new URL(meta('og:image'));
assert.equal(image.origin, 'https://stt.faysk.dev');
assert.notEqual(image.pathname, '/social-card.png', 'Invalidate old social preview URL');
const png = fs.readFileSync(path.join(root, image.pathname));
assert.equal(png.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
assert.equal(png.readUInt32BE(16), Number(meta('og:image:width')));
assert.equal(png.readUInt32BE(20), Number(meta('og:image:height')));
assert.ok(png.length < 5 * 1024 * 1024);
const schema = JSON.parse(html.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)[1]);
assert.equal(schema.url, meta('og:url'));
assert.equal(schema.name, 'stt / faysk');
const robots = fs.readFileSync(path.join(root, 'robots.txt'), 'utf8');
assert.match(robots, /Sitemap: https:\/\/stt\.faysk\.dev\/sitemap.xml/);
assert.doesNotMatch(robots, /Disallow: \/admin/,'Let crawlers observe admin noindex');
assert.match(fs.readFileSync(path.join(root, '_headers'), 'utf8'), /\/admin.html\s+X-Robots-Tag: noindex/);
assert.match(fs.readFileSync(path.join(root, 'admin.html'), 'utf8'), /content="noindex/);
assert.match(fs.readFileSync(path.join(root, 'sitemap.xml'), 'utf8'), /<loc>https:\/\/stt.faysk.dev\/<\/loc>/);
assert.ok(JSON.parse(fs.readFileSync(path.join(root, '../wrangler.stt.jsonc'), 'utf8')).assets.run_worker_first.includes('/index.html'));
assert.doesNotMatch(fs.readFileSync(path.join(root, '_redirects'), 'utf8'), /^\/index.html\s/m, 'ASSETS also fetches index internally: handle canonical redirect in Worker to avoid a home self-loop');
assert.doesNotMatch(html, /tts\.faysk|tts \/ faysk/);
console.log('SEO: canonical, social image, structured data, sitemap and private-page exclusion passed.');
