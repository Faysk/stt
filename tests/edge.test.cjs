const assert=require('node:assert/strict');
(async()=>{
 const {default:worker}=await import('../edge/worker.js');
 const env={ASSETS:{fetch:async request=>new Response(new URL(request.url).pathname==='/index.html'?'Home':'Asset',{status:['/index.html','/admin.html','/icon.svg'].includes(new URL(request.url).pathname)?200:404})}};
 const home=await worker.fetch(new Request('https://stt.faysk.dev/'),env);
 assert.equal(home.status,200,'Public root must serve the index when HTML handling is disabled');
 assert.equal(await home.text(),'Home');
 const duplicate=await worker.fetch(new Request('https://stt.faysk.dev/index.html?source=share'),env);
 assert.equal(duplicate.status,301);
 assert.equal(duplicate.headers.get('location'),'https://stt.faysk.dev/?source=share');
 assert.equal((await worker.fetch(new Request('https://stt.faysk.dev/admin.html'),env)).status,200);
 assert.equal((await worker.fetch(new Request('https://stt.faysk.dev/missing'),env)).status,404);
 const noOrigin=await worker.fetch(new Request('https://stt.faysk.dev/api/health'),env);
 assert.equal(noOrigin.status,503);
 assert.equal(noOrigin.headers.get('cache-control'),'no-store');
 assert.equal(noOrigin.headers.get('x-robots-tag'),'noindex, nofollow, noarchive');
 assert.equal(noOrigin.headers.get('x-content-type-options'),'nosniff');
 let forwarded;
 global.fetch=async(url,options)=>{forwarded={url:String(url),options};return new Response('{"online":true}',{headers:{'content-type':'application/json'}})};
 const response=await worker.fetch(new Request('https://stt.faysk.dev/api/health',{headers:{'CF-Connecting-IP':'192.0.2.1','x-stt-client':'spoofed','x-edge-key':'spoofed'}}),{...env,ORIGIN:'https://origin.example',EDGE_KEY:'test-edge'});
 assert.equal(response.status,200);
 assert.equal(forwarded.url,'https://origin.example/api/health');
 assert.equal(forwarded.options.headers.get('x-edge-key'),'test-edge');
 assert.equal(forwarded.options.headers.get('x-stt-client'),'192.0.2.1');
 assert.equal(response.headers.get('cache-control'),'no-store');
 assert.equal(response.headers.get('x-robots-tag'),'noindex, nofollow, noarchive');
 assert.equal(response.headers.get('x-content-type-options'),'nosniff');
 global.fetch=async()=>{const headers=new Headers();headers.append('set-cookie','__Host-stt_admin=session; Secure; HttpOnly; SameSite=Strict; Path=/');headers.append('set-cookie','__Host-stt_qr=; Max-Age=0; Secure; HttpOnly; Path=/');return new Response('{"authenticated":true}',{headers})};
 const login=await worker.fetch(new Request('https://stt.faysk.dev/api/admin/auth/qr/consume',{method:'POST',headers:{cookie:'__Host-stt_qr=browser','origin':'https://stt.faysk.dev','x-csrf-token':'csrf'},body:'{}'}),{...env,ORIGIN:'https://origin.example',EDGE_KEY:'test-edge'});
 assert.equal(login.headers.getSetCookie().length,2,'Edge must preserve session and binding cookie changes');
 assert.equal(login.headers.get('cache-control'),'no-store');
 global.fetch=async()=>{throw new Error('simulated unavailable origin')};
 const unavailable=await worker.fetch(new Request('https://stt.faysk.dev/api/health'),
   {...env,ORIGIN:'https://origin.example',EDGE_KEY:'test-edge'});
 assert.equal(unavailable.status,503);
 assert.equal(unavailable.headers.get('cache-control'),'no-store');
 assert.equal(unavailable.headers.get('x-robots-tag'),'noindex, nofollow, noarchive');
 console.log('Edge: public root, exact assets, missing route and authenticated API proxy passed.');
})().catch(error=>{console.error(error);process.exitCode=1});
