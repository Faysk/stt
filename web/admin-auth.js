/* QR approval contains no admin key; only the original HttpOnly cookie can consume it. */
(() => {
  const byId = id => document.getElementById(id);
  let bindingCsrf = '', currentRequest = '', pollTimer, clockTimer, expires = 0, generation = 0, busy = false;
  let enabled = false;
  const statusText = message => { byId('qr-status').textContent = message; };
  async function auth(path, body, token = '') {
    const response = await fetch('/api/admin/auth/' + path, {
      method: body === undefined ? 'GET' : 'POST', credentials: 'same-origin', cache: 'no-store',
      headers: {'content-type': 'application/json', 'x-stt-auth': '1', ...(token ? {'x-csrf-token': token} : {})},
      ...(body === undefined ? {} : {body: JSON.stringify(body)})
    });
    const data = await response.json();
    if (!response.ok) { const error = Error(typeof data.detail === 'string' ? data.detail : 'Não foi possível conectar.'); error.status = response.status; throw error; }
    return data;
  }
  function stop(message) {
    clearTimeout(pollTimer); clearInterval(clockTimer); generation++;
    bindingCsrf = ''; currentRequest = ''; byId('qr-frame').hidden = true; byId('qr-compare').hidden = true;
    byId('login-qr').removeAttribute('src'); byId('qr-cancel').hidden = true;
    byId('qr-link').removeAttribute('href');
    byId('qr-start').textContent = 'Gerar novo QR'; byId('qr-start').disabled = false;
    statusText(message);
  }
  function tick() {
    const seconds = Math.max(0, Math.ceil(expires - Date.now() / 1000));
    byId('qr-expiry').textContent = `Expira em ${seconds}s`;
    if (!seconds) stop('Este QR expirou. Gere outro para entrar.');
  }
  async function poll(run, failures = 0) {
    if (run !== generation) return;
    try {
      const data = await auth('qr/status', {request:currentRequest}, bindingCsrf);
      if (run !== generation) return;
      if (data.state === 'approved') {
        const session = await auth('qr/consume', {request:currentRequest}, bindingCsrf);
        if (run !== generation) return;
        stop('Acesso aprovado.');
        await window.STTAdmin.signIn(session.csrf);
        return;
      }
      if (!['pending', 'scanned'].includes(data.state)) {
        stop({expired: 'Este QR expirou.', rejected: 'Acesso rejeitado no celular.', cancelled: 'Pedido cancelado.', consumed: 'Este pedido já foi usado. Gere outro QR.'}[data.state] || 'Pedido encerrado.');
        return;
      }
      statusText(data.state === 'scanned' ? 'Aguardando aprovação no celular.' : 'Aguardando leitura do QR.');
      pollTimer = setTimeout(() => poll(run), 2500);
    } catch (error) {
      if (run !== generation) return;
      if ([401,403,404,409].includes(error.status)) { stop(error.message); return; }
      statusText('Conexão indisponível. Tentando novamente…');
      if (Date.now() / 1000 >= expires) stop(error.message);
      else pollTimer = setTimeout(() => poll(run, failures + 1), Math.min(10000, 2500 * (failures + 1)));
    }
  }
  async function start() {
    if (busy) return;
    busy = true; stop('Preparando QR…'); byId('qr-start').disabled = true;
    const run = generation;
    try {
      const data = await auth('qr/start', {});
      if (run !== generation || window.STTAdmin.isAuthenticated()) return;
      bindingCsrf = data.csrf; currentRequest = data.request; expires = data.expires;
      // SVG generated by the backend QR library; inert image, never innerHTML.
      byId('login-qr').src = 'data:image/svg+xml;base64,' + btoa(data.svg);
      const approval = new URL(data.url);
      if (approval.origin !== location.origin || approval.pathname !== '/admin-approve.html') throw Error('Endereço de aprovação inválido.');
      byId('qr-link').href = approval.href;
      byId('qr-code').textContent = data.code;
      byId('qr-frame').hidden = false; byId('qr-compare').hidden = false;
      byId('qr-cancel').hidden = false; byId('qr-start').disabled = true;
      tick(); clockTimer = setInterval(tick, 1000); poll(run);
    } catch (error) { if (run === generation) stop(error.message); }
    finally { busy = false; }
  }
  byId('qr-start').onclick = start;
  byId('qr-cancel').onclick = async () => {
    const token = bindingCsrf, request = currentRequest;
    try { await auth('qr/cancel', {request}, token); stop('Pedido cancelado.'); }
    catch (error) { statusText(error.message); }
  };
  window.addEventListener('stt:locked', () => { if (enabled) stop('Entre novamente para continuar.'); });
  // A successful legacy login also removes any still-visible QR and polling.
  const observer = new MutationObserver(() => { if (byId('admin-login').hidden && bindingCsrf) stop('Acesso autorizado.'); });
  observer.observe(byId('admin-login'), {attributes: true, attributeFilter: ['hidden']});
  (async () => {
    try {
      const config = await auth('config'); enabled = config.qr_enabled;
      byId('qr-login').hidden = !enabled; byId('legacy-login').hidden = !config.legacy_enabled;
      byId('legacy-login').open = !enabled && config.legacy_enabled;
      if (!enabled && !config.legacy_enabled) byId('admin-message').textContent = 'Acesso desativado. Use a recuperação local.';
      if (!enabled) return;
      try { const session = await auth('session'); await window.STTAdmin.signIn(session.csrf); return; }
      catch { /* No session: generate a fresh browser-bound login request. */ }
      await start();
    } catch { byId('admin-message').textContent = 'Não foi possível carregar as opções de acesso. Atualize a página.'; }
  })();
})();
